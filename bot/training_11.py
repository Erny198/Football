def build_training_plan_11(mode: str, formation: str, theme: str, duration: str) -> str:
    exercises = [e for e in _load_exercises() if theme in e.get("themes", [])]
    if not exercises:
        exercises = _load_exercises()[:4]
    selected = exercises[:4]

    mode_label = MODE_LABELS.get(mode, mode)
    theme_label = THEME_LABELS.get(theme, theme)
    form_info = FORMATION_INFO.get(formation, {})
    form_label = form_info.get("label", formation)

    if duration == "60":
        timing = ["0–10", "10–25", "25–42", "42–55", "55–60"]
    elif duration == "75":
        timing = ["0–12", "12–28", "28–50", "50–68", "68–75"]
    else:  # 90
        timing = ["0–15", "15–35", "35–58", "58–80", "80–90"]

    focus_by_mode = {
        "guardiola": "позиционирование до касания, промежуточные зоны, третий игрок, осмотр",
        "arteta": "реакция на потерю, прессинг-триггеры, компактность, страховка центра",
        "mixed": "с мячом — позиция и третий игрок; без мяча — реакция и компактность",
    }

    commands = []
    for e in selected:
        commands.extend(e.get("commands", [])[:2])
    commands = list(dict.fromkeys(commands))[:5]
    commands_str = ", ".join(commands) if commands else "Откройся!, Посмотри!, Давим!"

    lines = [
        f"<b>🧠 Тренировка 11 игроков — {_e(duration)} мин</b>",
        f"Схема: <b>{_e(form_label)}</b>  |  Режим: <b>{_e(mode_label)}</b>",
        f"Тема: <b>{_e(theme_label)}</b>",
        _SEP,
        "<b>Главная цель:</b>",
        f"Отработать «{_e(theme_label.lower())}» в схеме {_e(form_label)} на детях 10–14 лет.",
        "",
        "<b>Фокус тренера:</b>",
        _e(focus_by_mode.get(mode, focus_by_mode["mixed"])),
        "",
        "<b>Команды игрокам:</b>",
        f"<code>{_e(commands_str)}</code>",
        _SEP,
        "<b>📋 План:</b>",
        "",
    ]

    block_names = ["Разминка", "Технический блок", "Тактический блок", "Игровой блок", "Рефлексия"]
    for i, name in enumerate(block_names):
        if i < 4 and i < len(selected):
            e = selected[i]
            if mode == "guardiola":
                focus = e["guardiola_focus"]
            elif mode == "arteta":
                focus = e["arteta_focus"]
            else:
                focus = f"{e['guardiola_focus']} / {e['arteta_focus']}"
            lines.append(f"⏱ <b>{_e(timing[i])} мин — {_e(name)}</b>")
            lines.append(f"<i>{_e(e['name'])}</i>")
            lines.append(f"Цель: {_e(e['goal'])}")
            lines.append(f"Смотреть: {_e(focus)}")
        else:
            lines.append(f"⏱ <b>{_e(timing[i])} мин — {_e(name)}</b>")
            lines.append("Спросить игроков: что получилось, что мешало, один вывод.")
        lines.append("")

    lines += [
        _SEP,
        "<b>После тренировки зафиксировать:</b>",
        "1. Что команда поняла лучше по теме?",
        "2. Где теряли схему или позицию?",
        "3. Какую одну задачу взять на следующую тренировку?",
    ]
    return "\n".join(lines)
