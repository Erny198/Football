def get_scheme_text(formation: str) -> str:
    info = FORMATION_INFO.get(formation)
    if not info:
        return "Схема не найдена."
    return (
        f"<b>📐 Схема {_e(info['label'])}</b>\n"
        f"<i>{_e(info['style'])}</i>\n"
        f"{_SEP}\n"
        f"<code>{_e(info['scheme'])}</code>\n"
        f"{_SEP}\n"
        f"<b>Роли:</b>\n{info['roles']}\n"
        f"{_SEP}\n"
        f"<b>Ключевые принципы:</b>\n{_e(info['principles'])}"
    )


